  function addQ(q, right, wrongs, fact, d, grades) {
    if (!q) return;
    var opts = [right];
    for (var w = 0; w < wrongs.length && opts.length < 4; w++) {
      if (wrongs[w] && opts.indexOf(wrongs[w]) === -1 && wrongs[w] !== right) opts.push(wrongs[w]);
    }
    if (opts.length < 4) return;
    var key = q + '||' + right;
    if (seen[key]) return;
    seen[key] = 1;
    var rot = bank.length % 4;
    for (var r = 0; r < rot; r++) opts.push(opts.shift());
    bank.push({ q: q, a: opts, correct: opts.indexOf(right), fact: fact, d: d, grades: grades.slice() });
  }

